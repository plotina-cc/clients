#!/usr/bin/env python3
"""Tests for scripts/plotina-dart-tests.py — the helper that puts our dart tests
into a patched upstream checkout and gates the `flutter test` run.

Run: python3 -m unittest discover -s fluffychat/tests -p 'test_*.py' -v

No Flutter and no network here: `stage` and `precheck` run against throwaway
fixtures (our copies in `tests/`, a patches/ dir shaped like ours, a fake
upstream tree), and `gate` runs against captured `flutter test` output. The real
`flutter test` run is the workflow's job.
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]  # fluffychat/
SCRIPT = REPO / "scripts" / "plotina-dart-tests.py"

PATCH_HEAD = """\
# Plotina-Marker: plotina-patch-{n}
diff --git a/{path} b/{path}
--- /dev/null
+++ b/{path}
@@ -0,0 +1,2 @@
+// planted by patch {n}
+void main() {{}}
"""


def run(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(SCRIPT), *args],
        capture_output=True,
        text=True,
    )


class Fixture:
    """Our repo copy plus a patched-looking upstream tree, empty on disk."""

    def __init__(self, root: Path):
        self.root = root
        self.repo = root / "fluffychat"
        self.upstream = root / "upstream"
        (self.repo / "tests").mkdir(parents=True)
        (self.repo / "patches").mkdir()
        (self.upstream / "test").mkdir(parents=True)
        (self.upstream / "lib" / "l10n").mkdir(parents=True)
        (self.upstream / "lib" / "l10n" / "l10n.dart").write_text(
            "// generated by flutter gen-l10n\n", encoding="utf-8"
        )
        self.asset = self.repo / "plotina_dfn" / "assets" / "DeepFilterNet3_onnx.tar.gz"

    def repo_test(self, name: str, body: str = "// ours\n") -> Path:
        path = self.repo / "tests" / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8")
        return path

    def patch(self, number: str, *paths: str) -> Path:
        """A patch file that adds the given test paths, as 0016/0023/0027 do."""
        body = "\n".join(PATCH_HEAD.format(n=number, path=p) for p in paths)
        path = self.repo / "patches" / f"{number}-plotina-something.patch"
        path.write_text(body, encoding="utf-8")
        return path

    def planted(self, relpath: str, body: str = "// planted\n") -> Path:
        path = self.upstream / "test" / relpath
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8")
        return path

    def with_asset(self) -> None:
        self.asset.parent.mkdir(parents=True, exist_ok=True)
        self.asset.write_bytes(b"present\n")

    def stage(self) -> subprocess.CompletedProcess:
        return run("stage", "--repo", str(self.repo), "--upstream", str(self.upstream))

    def precheck(self) -> subprocess.CompletedProcess:
        return run("precheck", "--repo", str(self.repo), "--upstream", str(self.upstream))


class StageTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.fx = Fixture(Path(self.tmp.name))

    def test_copies_our_repo_tests_and_prints_them(self):
        self.fx.repo_test("intro_plotina_test.dart")
        self.fx.patch("0016", "test/utils/updater/update_channel_test.dart")
        self.fx.planted("utils/updater/update_channel_test.dart")
        result = self.fx.stage()
        self.assertEqual(result.returncode, 0, result.stderr)
        copied = self.fx.upstream / "test" / "plotina_ci" / "intro_plotina_test.dart"
        self.assertTrue(copied.is_file(), "our test was not copied into the tree")
        self.assertEqual(
            copied.read_text(encoding="utf-8"),
            "// ours\n",
            "the copy does not carry the repo file's content",
        )
        self.assertIn("test/plotina_ci/intro_plotina_test.dart", result.stdout.split())

    def test_runs_the_tests_our_patches_plant(self):
        # 0016/0020 plant test/utils/updater/*, 0025-0027 plant
        # test/plotina_*_test.dart; none of them has a copy in our tests/ dir,
        # and all of them exist only after the patches applied.
        self.fx.repo_test("intro_plotina_test.dart")
        self.fx.patch(
            "0016",
            "test/utils/updater/update_channel_test.dart",
            "test/utils/updater/update_manifest_test.dart",
        )
        self.fx.patch("0027", "test/plotina_push_cancel_test.dart")
        self.fx.planted("utils/updater/update_channel_test.dart")
        self.fx.planted("utils/updater/update_manifest_test.dart")
        self.fx.planted("plotina_push_cancel_test.dart")
        result = self.fx.stage()
        self.assertEqual(result.returncode, 0, result.stderr)
        ran = result.stdout.split()
        self.assertIn("test/utils/updater/update_channel_test.dart", ran)
        self.assertIn("test/utils/updater/update_manifest_test.dart", ran)
        self.assertIn("test/plotina_push_cancel_test.dart", ran)

    def test_a_planted_copy_of_one_of_our_tests_runs_once_from_our_copy(self):
        # 0023 plants test/plotina_contact_names_test.dart and the same test lives
        # in our tests/. Running both would double-count it, and the stale planted
        # copy — written by the patch, not by this commit — would be the one that
        # runs, so a fix to the test would not be the fix that is verified.
        self.fx.patch("0023", "test/plotina_contact_names_test.dart")
        self.fx.planted("plotina_contact_names_test.dart", "// stale copy from a patch\n")
        self.fx.repo_test("plotina_contact_names_test.dart", "// ours, newer\n")
        result = self.fx.stage()
        self.assertEqual(result.returncode, 0, result.stderr)
        ran = [
            line
            for line in result.stdout.split()
            if line.endswith("plotina_contact_names_test.dart")
        ]
        self.assertEqual(len(ran), 1, f"the same test would run twice: {ran}")
        self.assertEqual(
            ran[0],
            "test/plotina_ci/plotina_contact_names_test.dart",
            "the stale planted copy won over ours",
        )

    def test_upstream_suites_are_left_alone(self):
        # Running upstream's whole test/ dir is not an option: chat_list_test.dart
        # dies on a missing libvodozemac_bindings_dart.so even on a good build, and
        # a red step nobody can fix is a step people delete.
        self.fx.repo_test("intro_plotina_test.dart")
        self.fx.patch("0016", "test/utils/updater/update_channel_test.dart")
        self.fx.planted("utils/updater/update_channel_test.dart")
        self.fx.planted("homeserver_picker_test.dart")
        self.fx.planted("utils/set_up_vodozemac.dart")
        result = self.fx.stage()
        self.assertEqual(result.returncode, 0, result.stderr)
        ran = result.stdout.split()
        self.assertNotIn("test/homeserver_picker_test.dart", ran)
        self.assertNotIn("test/utils/set_up_vodozemac.dart", ran)

    def test_runs_repository_tests_that_no_patch_plants(self):
        # intro_plotina_test.dart and updater_manifest_test.dart exist only in
        # fluffychat/tests/: no patch plants them under upstream/test/, so a run
        # list derived from the patches alone would silently skip 8 tests.
        self.fx.repo_test("intro_plotina_test.dart")
        self.fx.repo_test("updater_manifest_test.dart")
        self.fx.patch("0016", "test/utils/updater/update_channel_test.dart")
        self.fx.planted("utils/updater/update_channel_test.dart")
        result = self.fx.stage()
        self.assertEqual(result.returncode, 0, result.stderr)
        ran = result.stdout.split()
        self.assertIn("test/plotina_ci/intro_plotina_test.dart", ran)
        self.assertIn("test/plotina_ci/updater_manifest_test.dart", ran)

    def test_refuses_an_empty_repo_tests_dir(self):
        # A silently empty list is how this step becomes decoration.
        result = self.fx.stage()
        self.assertNotEqual(result.returncode, 0, "an empty tests/ dir must fail the step")
        self.assertIn("no dart test", result.stderr.lower())

    def test_refuses_a_test_a_patch_did_not_plant(self):
        # If a patch stops planting its test (renamed, or the hunk was dropped
        # while the patch still applied), the list would shrink and fewer tests
        # would run. That has to fail here, not be discovered by the floor later.
        self.fx.repo_test("intro_plotina_test.dart")
        self.fx.patch("0027", "test/plotina_push_cancel_test.dart")
        result = self.fx.stage()
        self.assertNotEqual(result.returncode, 0, "a missing planted test passed the stage")
        self.assertIn("plotina_push_cancel_test.dart", result.stderr)

    def test_refuses_a_patch_that_plants_no_tests_at_all(self):
        # The floor is what catches this in the gate, but the reason must be
        # visible: our patches are supposed to plant tests, and an empty parsed
        # list means the parser and the patch layout drifted apart.
        self.fx.repo_test("intro_plotina_test.dart")
        self.fx.patch("0002", "lib/config/app_config.dart")
        result = self.fx.stage()
        self.assertNotEqual(result.returncode, 0, "zero planted tests passed the stage")
        self.assertIn("patch", result.stderr.lower())


class PrecheckTest(unittest.TestCase):
    """The trap: `flutter test` dies on a missing DeepFilterNet3 asset.

    The step must say why — a bare "Error detected in pubspec.yaml" from inside
    flutter is a 20-minute detour — and it must fail, never skip.
    """

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.fx = Fixture(Path(self.tmp.name))
        self.fx.repo_test("intro_plotina_test.dart")

    def test_fails_without_the_model_asset(self):
        result = self.fx.precheck()
        self.assertNotEqual(result.returncode, 0, "the step can run without the model asset")
        self.assertIn("fetch-model.sh", result.stderr)
        self.assertIn("DeepFilterNet3_onnx.tar.gz", result.stderr)

    def test_passes_with_the_model_asset(self):
        self.fx.with_asset()
        result = self.fx.precheck()
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_rejects_nothing_about_the_generated_l10n(self):
        # This runs before `flutter gen-l10n` in the workflow, so a tree without
        # lib/l10n/l10n.dart is *correct* here — the first CI run of the step was
        # red exactly because an earlier version of precheck demanded it. gen-l10n
        # reports its own failures.
        self.fx.with_asset()
        (self.fx.upstream / "lib" / "l10n" / "l10n.dart").unlink()
        result = self.fx.precheck()
        self.assertEqual(
            result.returncode,
            0,
            "precheck must not require the generated l10n: it runs before gen-l10n",
        )


class GateTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.log = Path(self.tmp.name) / "flutter-test.log"

    def gate(self, text: str, minimum: int = 60) -> subprocess.CompletedProcess:
        self.log.write_text(text, encoding="utf-8")
        return run("gate", "--log", str(self.log), "--min", str(minimum))

    def test_passes_on_a_real_passing_run(self):
        result = self.gate(
            "00:00 +0: loading /x/test/a_test.dart\n"
            "00:12 +59: /x/test/b_test.dart: last case\n"
            "00:12 +60: All tests passed!\n"
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("60", result.stdout)
        self.assertIn("passed", result.stdout.lower())

    def test_reports_skipped_tests_separately(self):
        result = self.gate("00:11 +58 ~2: All tests passed!\n", minimum=58)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("58", result.stdout)
        self.assertIn("2", result.stdout)

    def test_reads_the_github_actions_reporter_summary(self):
        # A non-TTY makes flutter switch reporters, and the compact counters never
        # appear — the CI log says `🎉 140 tests passed, 2 skipped.` and nothing
        # else. A gate that only understood the counters failed the first real CI
        # run of this step while the suite was completely green.
        result = self.gate(
            "00:00 +0: loading /x/test/a_test.dart\n"
            "🎉 140 tests passed, 2 skipped.\n"
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("140", result.stdout)
        self.assertIn("2", result.stdout)

    def test_reads_the_ci_summary_of_a_failed_run(self):
        result = self.gate("🎉 139 tests passed, 1 failed.\n")
        self.assertNotEqual(result.returncode, 0, "a failed CI summary passed the gate")
        self.assertIn("1", result.stderr)

    def test_fails_on_a_ci_summary_below_the_floor(self):
        result = self.gate("🎉 59 tests passed, 0 skipped.\n")
        self.assertNotEqual(result.returncode, 0, "a CI summary below the floor passed")
        self.assertIn("59", result.stderr)

    def test_fails_below_the_floor(self):
        result = self.gate("00:11 +59: All tests passed!\n")
        self.assertNotEqual(result.returncode, 0, "a run below the floor passed the gate")
        self.assertIn("59", result.stderr)

    def test_fails_on_a_failure_even_above_the_floor(self):
        result = self.gate(
            "00:10 +61 -1: /x/test/a_test.dart: a broken case\n"
            "00:11 +61 -1: Some tests failed.\n"
        )
        self.assertNotEqual(result.returncode, 0, "a failing test passed the gate")

    def test_fails_on_a_log_with_no_counters(self):
        # `flutter test` can die before printing a counter (no pub get, no
        # generated l10n, the missing asset). That must fail, not pass vacuously.
        result = self.gate(
            "Error detected in pubspec.yaml:\n"
            "No file or variants found for asset: "
            "packages/plotina_dfn/assets/DeepFilterNet3_onnx.tar.gz.\n"
        )
        self.assertNotEqual(result.returncode, 0, "a log with no counters passed the gate")
        self.assertIn("no test", result.stderr.lower())


if __name__ == "__main__":
    unittest.main()
